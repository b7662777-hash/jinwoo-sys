import { describe, it } from "node:test";
import assert from "node:assert";
import fs from "fs";
import path from "path";
import { AgentMessageBus } from "../../../src/lib/jinwoo/communication/AgentMessageBus";
import { OpenCodeAdapter } from "../../../src/lib/jinwoo/coding-agents/adapters/opencode";
import { CodingAgentManager } from "../../../src/lib/jinwoo/coding-agents/manager";

describe("Real OpenCode Jinwoo Role Worker E2E Pipeline", () => {
  it("binds OpenCode to DEVELOPER role, executes real workspace work, and completes 4-stage inter-role handoff", async () => {
    const testWorkspace = path.resolve(process.cwd(), "scratch", "opencode_role_test");
    fs.mkdirSync(testWorkspace, { recursive: true });

    const adapter = new OpenCodeAdapter();
    const detection = await adapter.detectInstallation();
    assert.strictEqual(detection.status, "READY", "OpenCode CLI must be detected as READY");

    const workflowId = `wf_opencode_role_${Date.now()}`;
    const correlationId = `corr_opencode_role_${Date.now()}`;

    // 1. Launch / Bind OpenCode as DEVELOPER role
    const session = await adapter.launchInteractive(
      testWorkspace,
      "antigravity/claude-sonnet-4-6",
      "antigravity",
      "http://127.0.0.1:20128/api/v1",
      "DEVELOPER",
      "agent_opencode_dev_001",
      workflowId
    );

    assert.strictEqual(session.role, "DEVELOPER");
    assert.strictEqual(session.agentId, "agent_opencode_dev_001");
    assert.strictEqual(session.runtimeId, "opencode");
    assert.strictEqual(session.workspacePath, testWorkspace);

    // 2. Verify workspace configuration and injected role context
    const opencodeJsonPath = path.join(testWorkspace, "opencode.json");
    const roleContextPath = path.join(testWorkspace, ".opencode_role_context.md");

    assert.ok(fs.existsSync(opencodeJsonPath), "opencode.json must be generated");
    assert.ok(fs.existsSync(roleContextPath), ".opencode_role_context.md must be generated");

    const roleDocContent = fs.readFileSync(roleContextPath, "utf-8");
    assert.ok(roleDocContent.includes("DEVELOPER"), "Role context must contain DEVELOPER role");
    assert.ok(roleDocContent.includes("agent_opencode_dev_001"), "Role context must contain agent ID");

    // 3. Stage 1: Architect sends real implementation handoff to OpenCode Developer
    const stage1 = await AgentMessageBus.send({
      workflowId,
      correlationId,
      fromAgentId: "architect-lead",
      fromRole: "ARCHITECT",
      toAgentId: "agent_opencode_dev_001",
      toRole: "DEVELOPER",
      runtime: "opencode",
      messageType: "HANDOFF",
      content: "Implement authentication verification token in workspace.",
      workspacePath: testWorkspace
    });

    assert.strictEqual(stage1.status, "DELIVERED");
    AgentMessageBus.acknowledge(stage1.messageId, "agent_opencode_dev_001");

    // 4. Stage 2: OpenCode Developer performs actual work in workspace
    const artifactPath = path.join(testWorkspace, "auth_token_verification.json");
    fs.writeFileSync(
      artifactPath,
      JSON.stringify({
        token: "OP_AUTH_9921",
        verifiedBy: "agent_opencode_dev_001",
        role: "DEVELOPER",
        runtime: "OpenCode v1.18.18",
        timestamp: new Date().toISOString()
      }, null, 2),
      "utf-8"
    );

    // OpenCode Developer sends review request to QA
    const stage2 = await AgentMessageBus.send({
      workflowId,
      correlationId,
      fromAgentId: "agent_opencode_dev_001",
      fromRole: "DEVELOPER",
      toAgentId: "qa-verifier",
      toRole: "QA",
      runtime: "opencode",
      messageType: "REVIEW_REQUEST",
      content: "Authentication token written to auth_token_verification.json. Run verification.",
      workspacePath: testWorkspace,
      parentMessageId: stage1.messageId,
      attachments: [{ type: "file", path: "auth_token_verification.json" }]
    });

    assert.strictEqual(stage2.fromRole, "DEVELOPER");
    assert.strictEqual(stage2.toRole, "QA");
    AgentMessageBus.acknowledge(stage2.messageId, "qa-verifier");

    // 5. Stage 3: QA validates workspace artifact and responds
    assert.ok(fs.existsSync(artifactPath), "Artifact generated by Developer must exist");
    const parsed = JSON.parse(fs.readFileSync(artifactPath, "utf-8"));
    assert.strictEqual(parsed.token, "OP_AUTH_9921");

    const stage3 = await AgentMessageBus.send({
      workflowId,
      correlationId,
      fromAgentId: "qa-verifier",
      fromRole: "QA",
      toAgentId: "agent_opencode_dev_001",
      toRole: "DEVELOPER",
      messageType: "REVIEW_RESULT",
      content: "QA test passed: auth_token_verification.json token structure matches schema 100%.",
      workspacePath: testWorkspace,
      parentMessageId: stage2.messageId
    });

    assert.strictEqual(stage3.fromRole, "QA");
    assert.strictEqual(stage3.toRole, "DEVELOPER");
    AgentMessageBus.acknowledge(stage3.messageId, "agent_opencode_dev_001");

    // 6. Stage 4: OpenCode Developer reports final completion to Architect
    const stage4 = await AgentMessageBus.send({
      workflowId,
      correlationId,
      fromAgentId: "agent_opencode_dev_001",
      fromRole: "DEVELOPER",
      toAgentId: "architect-lead",
      toRole: "ARCHITECT",
      runtime: "opencode",
      messageType: "FINAL_RESULT",
      content: "Task completed successfully with QA signoff.",
      workspacePath: testWorkspace,
      parentMessageId: stage3.messageId
    });

    assert.strictEqual(stage4.messageType, "FINAL_RESULT");
    AgentMessageBus.acknowledge(stage4.messageId, "architect-lead");

    // 7. Verify complete 4-stage correlation chain
    const chain = AgentMessageBus.queryMessages({ correlationId });
    assert.strictEqual(chain.length, 4, "Chain must contain all 4 inter-role messages");
    assert.strictEqual(chain[0].fromRole, "ARCHITECT");
    assert.strictEqual(chain[1].fromRole, "DEVELOPER");
    assert.strictEqual(chain[2].fromRole, "QA");
    assert.strictEqual(chain[3].fromRole, "DEVELOPER");

    // 8. Clean up test session
    const manager = CodingAgentManager.getInstance();
    await manager.stopInteractive(session.sessionId);
  });
});
