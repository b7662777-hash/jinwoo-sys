"use client";

import React, { useState } from "react";
import { useJinwooWorkspace } from "@/app/(jinwoo)/jinwoo/context";

export default function TasksPage() {
  const tabs = ["All", "Pending", "Ready", "Running", "Blocked", "Completed", "Failed"];
  const [activeTab, setActiveTab] = useState("All");
  const { state } = useJinwooWorkspace();

  const tasks = state.plan?.tasks || [];

  return (
    <div style={{ padding: '0 24px 24px 24px', color: '#f3f4f6' }}>
      <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'center', marginBottom: '24px' }}>
        <h1 style={{ fontSize: '24px', fontWeight: 'bold' }}>Task Queue</h1>
      </div>

      <div style={{ display: 'flex', gap: '16px', borderBottom: '1px solid #1f2937', marginBottom: '24px', overflowX: 'auto' }}>
        {tabs.map(tab => (
          <button 
            key={tab}
            onClick={() => setActiveTab(tab)}
            style={{ 
              background: 'none', border: 'none', padding: '8px 4px', cursor: 'pointer', 
              color: activeTab === tab ? '#a78bfa' : '#9ca3af', 
              borderBottom: activeTab === tab ? '2px solid #8b5cf6' : '2px solid transparent',
              fontWeight: activeTab === tab ? '600' : '400',
              fontSize: '14px',
              whiteSpace: 'nowrap'
            }}
          >
            {tab}
          </button>
        ))}
      </div>

      <div style={{ display: 'flex', flexDirection: 'column', gap: '16px' }}>
         {tasks.length === 0 ? (
            <div style={{ padding: '48px', textAlign: 'center', backgroundColor: '#111827', borderRadius: '12px', border: '1px dashed #374151' }}>
              <div style={{ fontSize: '32px', marginBottom: '12px' }}>✓</div>
              <h2 style={{ fontSize: '18px', marginBottom: '8px', color: '#e5e7eb' }}>No Tasks</h2>
              <p style={{ color: '#9ca3af' }}>There are no tasks generated by the active workflow.</p>
            </div>
         ) : (
            tasks.map((task: any, idx) => (
              <div key={idx} style={{ background: '#111827', border: '1px solid #374151', borderRadius: '8px', padding: '16px', display: 'flex', justifyContent: 'space-between', alignItems: 'center' }}>
                <div style={{ display: 'flex', flexDirection: 'column', gap: '4px' }}>
                   <div style={{ color: '#e5e7eb', fontSize: '15px', fontWeight: '600' }}>{task.id}</div>
                   <div style={{ color: '#9ca3af', fontSize: '13px' }}>Role: <span style={{ color: '#a78bfa', fontWeight: '500' }}>{task.role}</span> | Model: {task.recommendedModel || 'Pending'}</div>
                </div>
                <div style={{ display: 'flex', alignItems: 'center', gap: '16px' }}>
                   <span style={{ backgroundColor: task.status === 'COMPLETED' ? 'rgba(16, 185, 129, 0.1)' : (task.status === 'RUNNING' ? 'rgba(59, 130, 246, 0.1)' : 'rgba(107, 114, 128, 0.1)'), color: task.status === 'COMPLETED' ? '#34d399' : (task.status === 'RUNNING' ? '#60a5fa' : '#9ca3af'), padding: '4px 12px', borderRadius: '12px', fontSize: '11px', fontWeight: '600' }}>
                     {task.status || 'PENDING'}
                   </span>
                   <button style={{ backgroundColor: 'transparent', border: '1px solid #4b5563', color: '#d1d5db', padding: '6px 12px', borderRadius: '4px', fontSize: '12px', cursor: 'pointer' }}>View Details</button>
                </div>
              </div>
            ))
         )}
      </div>
    </div>
  );
}
